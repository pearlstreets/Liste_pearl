def set_nested(d, dotted_key, value):
    parts = dotted_key.split('.')
    node = d
    for p in parts[:-1]:
        if p not in node or not isinstance(node[p], dict):
            node[p] = {}
        node = node[p]
    node[parts[-1]] = value

